  /// Vérifie si un mot est un mot anglais valide du dictionnaire
  static bool isValidWord(String word) {
    final clean = word.trim().toLowerCase();
    return _words.contains(clean);
  }

  /// Recherche un mot commençant par une lettre donnée
  static List<String> getWordsStartingWith(String letter) {
    final l = letter.trim().toLowerCase();
    return _words.where((w) => w.startsWith(l)).toList();
  }

  /// Sélectionne un mot pour l'IA selon la difficulté
  static String? findAiWord(String startingLetter, Set<String> usedWords, int difficulty) {
    final candidates = getWordsStartingWith(startingLetter)
        .where((w) => !usedWords.contains(w))
        .toList();

    if (candidates.isEmpty) return null;

    candidates.sort((a, b) => a.length.compareTo(b.length));

    switch (difficulty) {
      case 0: // Débutant (mots courts 3-5 lettres)
        final easy = candidates.where((w) => w.length <= 5).toList();
        return easy.isNotEmpty ? (easy..shuffle()).first : candidates.first;
      case 1: // Normal (mots moyens 5-7 lettres)
        final med = candidates.where((w) => w.length >= 5 && w.length <= 8).toList();
        return med.isNotEmpty ? (med..shuffle()).first : candidates[candidates.length ~/ 2];
      default: // Maître (mots longs et stratégiques)
        return candidates.last;
    }
  }
